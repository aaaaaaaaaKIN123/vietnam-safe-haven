phase3_13_strategy_labels <- c(
  unhedged_vnindex = "Unhedged VNIndex",
  static_best_trailing = "Static trailing best",
  equal_safe_haven_basket = "Equal safe-haven basket",
  dcc_trailing_best = "DCC trailing best",
  adcc_trailing_best = "aDCC trailing best",
  ml_softmax_adaptive = "ML adaptive"
)

phase3_13_cumulative_returns <- function(performance) {
  strategies <- unique(performance$strategy)
  out <- data.frame()
  for (strategy in strategies) {
    sub <- performance[performance$strategy == strategy, , drop = FALSE]
    sub <- sub[order(sub$date), , drop = FALSE]
    sub$cumulative_return_pct <- (cumprod(1 + sub$return_pct / 100) - 1) * 100
    out <- rbind(out, sub)
  }
  out
}

phase3_13_plot_cumulative_return <- function(performance, config) {
  figure_dir <- file.path(config$outputs$figures_dir, "adaptive_ml")
  ensure_dir(figure_dir)
  cumulative <- phase3_13_cumulative_returns(performance)
  strategies <- names(phase3_13_strategy_labels)
  strategies <- strategies[strategies %in% cumulative$strategy]
  line_types <- seq_along(strategies)
  y_range <- range(cumulative$cumulative_return_pct, na.rm = TRUE)
  dates <- as.Date(cumulative$date)

  draw_plot <- function(path, device) {
    if (device == "png") {
      png(path, width = 1200, height = 760, res = 150)
    } else {
      svg(path, width = 8, height = 5.1)
    }
    old_par <- par(no.readonly = TRUE)
    on.exit({
      par(old_par)
      dev.off()
    })
    par(mar = c(4.5, 4.8, 3.2, 1.2), family = "sans")
    plot(
      range(dates, na.rm = TRUE),
      y_range,
      type = "n",
      xlab = "Date",
      ylab = "Cumulative return (%)",
      main = "Out-of-sample cumulative hedged return"
    )
    grid(col = "grey85", lty = "solid")
    abline(h = 0, col = "grey35", lty = 3)
    for (i in seq_along(strategies)) {
      strategy <- strategies[i]
      sub <- cumulative[cumulative$strategy == strategy, , drop = FALSE]
      lines(as.Date(sub$date), sub$cumulative_return_pct, col = "black", lwd = ifelse(strategy == "ml_softmax_adaptive", 2.2, 1.2), lty = line_types[i])
    }
    legend(
      "topleft",
      legend = unname(phase3_13_strategy_labels[strategies]),
      col = "black",
      lty = line_types,
      lwd = ifelse(strategies == "ml_softmax_adaptive", 2.2, 1.2),
      bty = "n",
      cex = 0.78
    )
  }

  png_path <- file.path(figure_dir, "ml_cumulative_hedged_return.png")
  svg_path <- file.path(figure_dir, "ml_cumulative_hedged_return.svg")
  draw_plot(png_path, "png")
  draw_plot(svg_path, "svg")
  c(png_path, svg_path)
}

phase3_13_plot_feature_importance <- function(importance, config) {
  figure_dir <- file.path(config$outputs$figures_dir, "adaptive_ml")
  ensure_dir(figure_dir)
  importance <- importance[order(-importance$importance_abs_softmax_coefficient), , drop = FALSE]
  importance <- head(importance, 12)
  importance <- importance[rev(seq_len(nrow(importance))), , drop = FALSE]

  draw_plot <- function(path, device) {
    if (device == "png") {
      png(path, width = 1100, height = 760, res = 150)
    } else {
      svg(path, width = 7.4, height = 5.1)
    }
    old_par <- par(no.readonly = TRUE)
    on.exit({
      par(old_par)
      dev.off()
    })
    par(mar = c(4.5, 10.8, 3.2, 1.2), family = "sans")
    barplot(
      importance$importance_abs_softmax_coefficient,
      names.arg = importance$feature,
      horiz = TRUE,
      las = 1,
      col = "grey70",
      border = "black",
      xlab = "Mean absolute softmax coefficient",
      main = "Adaptive ML feature importance"
    )
    grid(nx = NA, ny = NULL, col = "grey88", lty = "solid")
  }

  png_path <- file.path(figure_dir, "ml_shap_summary.png")
  svg_path <- file.path(figure_dir, "ml_shap_summary.svg")
  draw_plot(png_path, "png")
  draw_plot(svg_path, "svg")
  c(png_path, svg_path)
}

phase3_13_append_figure_report <- function(report_path, figures) {
  lines <- c(
    "",
    "## Figure Files Generated by R Wrapper",
    "",
    paste0("- `", normalizePath(figures, winslash = "/", mustWork = FALSE), "`")
  )
  cat(paste(lines, collapse = "\n"), file = report_path, append = TRUE)
}

run_phase3_13_adaptive_ml <- function(
  control_path = "src/models/model_control.yaml",
  method_map_path = "src/models/model_method_map.yaml",
  strict_packages = FALSE
) {
  config <- read_model_control(control_path)
  method_map <- read_model_method_map(method_map_path)
  validation <- validate_model_control(config, method_map, strict_packages = strict_packages)
  if (!validation$ok) {
    stop(paste(validation$errors, collapse = "\n"), call. = FALSE)
  }
  ensure_output_dirs(config)
  ensure_dir(file.path(config$outputs$tables_dir, "adaptive_ml"))
  ensure_dir(file.path(config$outputs$figures_dir, "adaptive_ml"))
  append_log("Phase 3.13 adaptive ML started.", config)

  script_path <- "src/models/python/03_adaptive_hedge_ml.py"
  status <- system2("python", script_path)
  if (!identical(status, 0L)) {
    stop("Python adaptive ML script failed.", call. = FALSE)
  }

  performance_path <- file.path(config$outputs$tables_dir, "adaptive_ml", "ml_walk_forward_performance.csv")
  benchmark_path <- file.path(config$outputs$tables_dir, "adaptive_ml", "ml_benchmark_comparison.csv")
  importance_path <- file.path(config$outputs$tables_dir, "adaptive_ml", "ml_feature_importance.csv")
  report_path <- "data/metadata/phase3_13_adaptive_ml_report.md"

  performance <- read.csv(performance_path, stringsAsFactors = FALSE, check.names = FALSE, fileEncoding = "UTF-8-BOM")
  benchmark <- read.csv(benchmark_path, stringsAsFactors = FALSE, check.names = FALSE, fileEncoding = "UTF-8-BOM")
  importance <- read.csv(importance_path, stringsAsFactors = FALSE, check.names = FALSE, fileEncoding = "UTF-8-BOM")
  performance$date <- as.Date(performance$date)

  figures <- c(
    phase3_13_plot_cumulative_return(performance, config),
    phase3_13_plot_feature_importance(importance, config)
  )
  phase3_13_append_figure_report(report_path, figures)
  append_log("Phase 3.13 adaptive ML finished.", config)

  list(
    performance = performance,
    benchmark = benchmark,
    importance = importance,
    figures = figures,
    report = report_path
  )
}

is_direct_rscript_call <- function(file) {
  args <- commandArgs(trailingOnly = FALSE)
  file_arg <- sub("^--file=", "", args[grepl("^--file=", args)])
  length(file_arg) > 0 &&
    identical(
      normalizePath(file_arg[1], winslash = "/", mustWork = FALSE),
      normalizePath(file, winslash = "/", mustWork = FALSE)
    )
}

if (!interactive() && is_direct_rscript_call("src/models/run_phase3_13_adaptive_ml.R")) {
  result <- run_phase3_13_adaptive_ml()
  cat("Phase 3.13 adaptive ML completed.\n")
  cat(sprintf("Performance rows: %s\n", nrow(result$performance)))
  cat(sprintf("Benchmark rows: %s\n", nrow(result$benchmark)))
  cat(sprintf("Feature rows: %s\n", nrow(result$importance)))
  cat(sprintf("Report: %s\n", result$report))
}
